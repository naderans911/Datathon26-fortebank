@router.get("/api/ui/jobs/{job_id}/media/{filename:path}", tags=["Browser UI"])
def job_media(job_id: str, filename: str, request: Request, session=Depends(require_session)):
    job = get_job(request, job_id, owner=session["id"])
    if job["status"] != "done":
        raise HTTPException(404, detail="Media not found")
    allowed = {frame["filename"] for event in job["result"]["events"] for frame in event["evidence_frames"]}
    if job["result"].get("preview_available"):
        allowed.add("preview.mp4")
    if filename not in allowed:
        raise HTTPException(404, detail="Media not found")
    try:
        path = media_path(request.app.state.settings.storage_dir / "jobs" / job_id, filename)
    except ValueError:
        raise HTTPException(404, detail="Media not found") from None
    if not path.is_file():
        raise HTTPException(404, detail="Media not found")
    return FileResponse(path, media_type="video/mp4" if filename == "preview.mp4" else "image/jpeg",
                        headers={"Cache-Control": "private, no-store", "X-Content-Type-Options": "nosniff"})


@router.delete("/api/ui/jobs/{job_id}", status_code=204, tags=["Browser UI"])
def delete_job(job_id: str, request: Request, session=Depends(require_csrf)):
    job = get_job(request, job_id, owner=session["id"])
    if job["status"] not in ("done", "failed"):
        raise HTTPException(409, detail={"code": "job_active", "message": "Wait until processing stops before deleting this job."})
    jobs_root = (request.app.state.settings.storage_dir / "jobs").resolve()
    directory = (jobs_root / job_id).resolve()
    if directory.parent != jobs_root:
        raise HTTPException(409, detail={"code": "storage_unavailable", "message": "The stored media location is invalid. Contact the operator."})
    try:
        if directory.exists():
            shutil.rmtree(directory)
    except OSError:
        raise HTTPException(409, detail={"code": "media_busy", "message": "Media is currently in use. Try deleting this job again shortly."}) from None
    request.app.state.store.delete(job_id)
    return Response(status_code=204)


@router.get("/api/ui/demo/{kind}", tags=["Synthetic demo"])
def demo(kind: str, request: Request, session=Depends(require_session)):
    require_same_origin(request)
    settings = request.app.state.settings
    if not settings.enable_demo or kind not in {"positive", "negative", "failed"}:
        raise HTTPException(404, detail="Demo not found")
    from backend.app.services.demo import build_demo
    # Rate-limit demo generation as well: it writes local media and uses FFmpeg.
    store = request.app.state.store
    used = storage_bytes(settings.storage_dir)
    if used + 10 * 1024 * 1024 > settings.max_storage_mb * 1024 * 1024:
        raise HTTPException(503, detail={"code": "capacity_unavailable", "message": "Storage is full. Purge retained jobs."})
    with store.connect() as connection:
        connection.execute("BEGIN IMMEDIATE")
        subjects = [f"demo:{session['id']}", f"demo-ip:{token_hash(request.client.host if request.client else 'unknown')}"]
        now = time.time()
        connection.execute("DELETE FROM rate_events WHERE occurred_at<?", (now - 3600,))
        for subject in subjects:
            count = connection.execute("SELECT COUNT(*) FROM rate_events WHERE subject=?", (subject,)).fetchone()[0]
            if count >= settings.upload_rate_per_hour:
                raise HTTPException(429, detail={"code": "rate_limited", "message": "Demo generation rate limit reached."})
        for subject in subjects:
            connection.execute("INSERT INTO rate_events VALUES (?,?)", (subject, now))
    if not request.app.state.demo_slots.acquire(blocking=False):
        raise HTTPException(503, detail={"code": "demo_busy", "message": "A synthetic demo is being prepared. Try again shortly."})
    try:
        payload = build_demo(kind, settings)
        store.add_demo(payload, session["id"], settings.storage_dir / "jobs" / payload["job_id"])
        return ui_payload(store.get(payload["job_id"]))
    except Exception:
        raise HTTPException(503, detail={"code": "demo_unavailable", "message": "Synthetic demo generation failed. Check the local FFmpeg installation."}) from None
    finally:
        request.app.state.demo_slots.release()
