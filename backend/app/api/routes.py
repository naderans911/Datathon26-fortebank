router = APIRouter()
JOB_ID = re.compile(r"^[a-f0-9]{32}$")


def storage_bytes(root: Path) -> int:
    total = 0
    if root.exists():
        for path in root.rglob("*"):
            try:
                if path.is_file():
                    total += path.stat().st_size
            except FileNotFoundError:
                pass
    return total


def get_job(request: Request, job_id: str, owner: str | None = None, judge: bool = False):
    if not JOB_ID.fullmatch(job_id):
        raise HTTPException(404, detail="Job not found")
    store = request.app.state.store
    store.recover(request.app.state.settings.worker_heartbeat_seconds * 3)
    job = store.get(job_id)
    if job is None or (judge and job["is_demo"]) or (owner is not None and job["owner"] != owner):
        raise HTTPException(404, detail="Job not found")
    return job


def ui_payload(job: dict):
    terminal = job["status"] in ("done", "failed")
    payload = {
        "job_id": job["id"], "status": job["status"] if terminal else "processing",
        "stage": job["stage"], "created_at": job["accepted_at"], "updated_at": job["updated_at"],
        "elapsed_sec": max(0, (job["updated_at"] if terminal else time.time()) - job["accepted_at"]),
        "filename": job["filename"], "size_bytes": job["size_bytes"], "demo": bool(job["is_demo"]),
    }
    if job["error"]:
        payload["error"] = job["error"]
    if job["status"] == "done":
        result = copy.deepcopy(job["result"])
        result["verdict"] = "violation" if result["events"] else "no_violation"
        for event in result["events"]:
            for frame in event["evidence_frames"]:
                frame["url"] = f"/api/ui/jobs/{job['id']}/media/{quote(frame['filename'], safe='/')}"
                frame.pop("filename", None)
        result["preview_url"] = f"/api/ui/jobs/{job['id']}/media/preview.mp4" if result.get("preview_available") else None
        payload["result"] = result
    return payload


async def accept_upload(request: Request, file: UploadFile, owner: str | None):
    settings, store = request.app.state.settings, request.app.state.store
    status, rules = await run_in_threadpool(get_readiness, settings, store, request.app.state.detector)
    if not status["ready"]:
        await file.close()
        raise HTTPException(503, detail={"code": "engine_not_ready", "message": "Real analysis is unavailable.", "reasons": status["reasons"]})
    # Names are display-only. The storage filename is always generated by the server.
    filename = (file.filename or "video.mov").replace("\\", "/").split("/")[-1][:200]
    filename = "".join(character for character in filename if character.isprintable())
    if Path(filename).suffix.lower() not in {".mov", ".mp4", ".m4v", ".mkv"}:
        await file.close()
        raise HTTPException(415, detail={"code": "unsupported_format", "message": "Select a .mov, .mp4, .m4v or .mkv video. Actual media will be validated locally."})
    job_id = uuid.uuid4().hex
    directory = settings.storage_dir / "jobs" / job_id
    snapshot = [rule.model_dump(mode="json") if hasattr(rule, "model_dump") else dict(rule) for rule in rules]
    job = {"id": job_id, "owner": owner, "filename": filename, "source_path": str(directory / "source.mov"),
           "rules_snapshot": snapshot, "detector_version": status["detector_name"]}
    subjects = []
    if owner:
        subjects = [f"ip:{token_hash(request.client.host if request.client else 'unknown')}", f"session:{owner}"]
    try:
        store.recover(settings.worker_heartbeat_seconds * 3)
        used = await run_in_threadpool(storage_bytes, settings.storage_dir)
        store.reserve(job, settings, subjects, used)
    except CapacityError as exc:
        await file.close()
        raise HTTPException(503, detail={"code": "capacity_unavailable", "message": str(exc)}) from None
    except RateLimitError as exc:
        await file.close()
        raise HTTPException(429, detail={"code": "rate_limited", "message": str(exc)}, headers={"Retry-After": "3600"}) from None
    try:
        directory.mkdir(parents=True, exist_ok=False)
        digest = hashlib.sha256()
        size = 0
        with (directory / "upload.part").open("wb") as target:
            while chunk := await file.read(1024 * 1024):
                size += len(chunk)
                if size > settings.max_upload_bytes:
                    raise HTTPException(413, detail={"code": "upload_too_large", "message": "The upload exceeds the configured size limit."})
                digest.update(chunk)
                target.write(chunk)
        if not size:
            raise HTTPException(422, detail={"code": "empty_upload", "message": "The selected file is empty."})
        (directory / "upload.part").replace(directory / "source.mov")
        store.accept(job_id, size, digest.hexdigest(), settings.job_deadline_seconds, settings.max_job_output_mb * 1024 * 1024)
    except BaseException:
        store.delete(job_id)
        shutil.rmtree(directory, ignore_errors=True)
        raise
    finally:
        await file.close()
    return {"job_id": job_id}


@router.post("/api/v1/analyze", status_code=202, response_model=AcceptedJob, dependencies=[Depends(require_judge)], tags=["Judge API"])
async def judge_analyze(request: Request, file: UploadFile = File(...)):
    return await accept_upload(request, file, owner=None)


@router.get("/api/v1/jobs/{job_id}", response_model=JudgeProcessing | JudgeDone | JudgeFailed, dependencies=[Depends(require_judge)], tags=["Judge API"])
def judge_job(job_id: str, request: Request):
    job = get_job(request, job_id, judge=True)
    if job["status"] == "failed":
        return {"job_id": job_id, "status": "failed", "error": job["error"]}
    if job["status"] != "done":
        return {"job_id": job_id, "status": "processing"}
    violations = []
    try:
        for event in job["result"]["events"]:
            frames = []
            for frame in event["evidence_frames"]:
                path = media_path(request.app.state.settings.storage_dir / "jobs" / job_id, frame["filename"])
                frames.append({"timestamp_sec": frame["timestamp_sec"], "image_base64": base64.b64encode(path.read_bytes()).decode("ascii")})
            rule = event["rule"]
            reference = rule.get("document_title", "")
            if rule.get("section_or_paragraph"):
                reference += f", {rule['section_or_paragraph']}"
            violations.append({"type": event["type"], "timecode_sec": event["timecode_sec"],
                "description": f"Observation: {event['observation']} Interpretation: {event['interpretation']} Source: {reference}. Human review required.",
                "evidence_frames": frames})
    except (OSError, ValueError):
        raise HTTPException(503, detail={"code": "evidence_unavailable", "message": "Stored evidence is unavailable. The completed result cannot be served."}) from None
    return {"job_id": job_id, "status": "done", "verdict": "violation" if violations else "no_violation", "violations": violations}


@router.get("/api/ui/session", tags=["Browser UI"])
def session(request: Request, response: Response):
    require_same_origin(request)
    existing = request.app.state.store.session(request.cookies.get(COOKIE_NAME))
    if existing:
        return {"csrf_token": existing["csrf"]}
    settings = request.app.state.settings
    token, csrf = request.app.state.store.new_session(settings.session_hours)
    response.set_cookie(COOKIE_NAME, token, httponly=True, secure=settings.secure_cookies,
                        samesite="lax", max_age=settings.session_hours * 3600, path="/api/ui")
    return {"csrf_token": csrf}


